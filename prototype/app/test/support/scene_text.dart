import 'package:archive_prototype/scene/text_paragraph.dart';

// 검사용 글줄 준비.
//
// 그리는 쪽은 한 장면에 새 글줄을 정해진 만큼만 준비한다 — 40개 · 1.5ms(보관이 빈 첫 장면은 6ms)이고, 시간은 **실제 시간**으로 잰다.
// 예산이 떨어지면 그 이름은 그 장면에서 빠지고(`starved`) 다음 장면에 이어 간다. 앱은 다음 장면을 청해 채우지만,
// 장면 하나를 그려 놓고 재는 검사는 '어느 이름까지 실렸는가'가 그 순간 기기가 얼마나 바쁜지에 달리게 된다 —
// 전체 검사를 나란히 돌릴 때 글줄 몇 개를 짓는 사이에 6ms를 넘기면 이름이 빠져, 따로 돌리면 늘 통과하는 검사가 가끔 떨어졌다.

/// 장면마다의 예산을 풀어 둔 글줄 준비(글줄 방식). **이름이 다 실린 장면 하나**를 재는 검사는 이것으로 그리개를 짓는다 —
/// 한 장면에 모든 이름이 준비되어, 결과가 기기의 형편과 무관해진다.
/// 예산이 떨어진 장면을 이어 그리는 길은 예산을 손수 정하는 검사가 본다(painter_test의 '새 글줄은 장면마다 …' · batch_test · glyph_atlas_test).
ParagraphText unbudgetedText() => ParagraphText()
  ..maxNewPerFrame = 1 << 20
  ..budgetMicros = 1 << 40;
